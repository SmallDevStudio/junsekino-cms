export function getDocsCategories(locale = "en") {
  const safeLocale = locale === "th" ? "th" : "en";

  return DOCS_CATEGORIES.map((category) => ({
    ...category,

    title: category.title?.[safeLocale] || category.title?.en || category.id,

    description:
      category.description?.[safeLocale] || category.description?.en || "",

    items: category.items.map((item) => ({
      ...item,

      categoryId: category.id,

      categoryTitle:
        category.title?.[safeLocale] || category.title?.en || category.id,

      title: item.title?.[safeLocale] || item.title?.en || item.id,

      description: item.description?.[safeLocale] || item.description?.en || "",
    })),
  }));
}

export function getDocsSearchItems(locale = "en") {
  return getDocsCategories(locale).flatMap((category) => category.items);
}

export function findDocsArticle({
  categoryId,

  articleId,

  locale = "en",
}) {
  const category = getDocsCategories(locale).find(
    (item) => item.id === categoryId,
  );

  if (!category) {
    return null;
  }

  const article = category.items.find((item) => item.id === articleId);

  if (!article) {
    return null;
  }

  return {
    category,
    article,
  };
}
